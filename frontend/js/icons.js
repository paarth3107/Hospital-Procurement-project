export function icon(name, size = 18) {
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name] || ""}</svg>`;
}

// Fills every element with a data-icon attribute (sidebar items, group headers).
export function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    if (el.querySelector(":scope > svg.nav-icon")) return;
    el.insertAdjacentHTML("afterbegin", icon(el.dataset.icon, 18).replace("<svg ", '<svg class="nav-icon" '));
  });
}
